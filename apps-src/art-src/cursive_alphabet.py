# Bands: asc .18 | midline .30 | baseline .58 | desc .75   (caps: top .20, base .65)
import math, json
A,M,B,D = .18,.30,.58,.75
CT, CB = .20, .65

def q(p0,p1,p2,n=8):
    return [(p0[0]*(1-t)**2+2*p1[0]*(1-t)*t+p2[0]*t*t,
             p0[1]*(1-t)**2+2*p1[1]*(1-t)*t+p2[1]*t*t) for t in [i/n for i in range(n+1)]]
def arc(cx,cy,rx,ry,a0,a1,n=14):
    return [(cx+rx*math.cos(math.radians(a0+(a1-a0)*i/n)),
             cy+ry*math.sin(math.radians(a0+(a1-a0)*i/n))) for i in range(n+1)]
def J(*parts):
    out=[]
    for p in parts:
        for pt in p:
            if not out or abs(pt[0]-out[-1][0])>1e-4 or abs(pt[1]-out[-1][1])>1e-4: out.append(pt)
    return out
def R(pts,d=3): return [[round(x,d),round(y,d)] for x,y in pts]
def entry(x, top=M):  return q((x-.055,B),(x-.02,B+.005),(x,top+.02),6)
def exitv(x,y=B):     return q((x,y),(x+.03,y+.005),(x+.06,y-.055),5)
RY=(B-M)/2; CY=(M+B)/2
def oval(cx,start=-45):   return arc(cx,CY,.055,RY,start,start-360,22)
def retrace(cx,a0=-45,a1=80): return arc(cx,CY,.055,RY,a0,a1,8)
def topright(cx,a=-45):   return (cx+.055*math.cos(math.radians(a)),CY+RY*math.sin(math.radians(a)))
def lead(cx):             return q((.40,B),(.42,B-.06),topright(cx))
def ascloop(x):       return J(q((x,B),(x-.035,M-.02),(x-.005,A),7), q((x-.005,A),(x+.028,M-.04),(x,B),7))
def descloop(x, right=False):
    if right: return J(q((x,B),(x+.02,D-.03),(x-.005,D),6), q((x-.005,D),(x-.055,D-.02),(x-.03,B-.03),6))
    return J(q((x,B),(x+.015,D-.02),(x-.01,D),6), q((x-.01,D),(x-.06,D-.02),(x-.035,B-.04),6))
def arch(x0,x1):      return J(q((x0,B),(x0,M+.01),((x0+x1)/2,M),6), q(((x0+x1)/2,M),(x1,M+.01),(x1,B),6))

